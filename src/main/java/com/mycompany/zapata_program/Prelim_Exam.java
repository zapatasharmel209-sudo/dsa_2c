        player1Health--; lblP1Health.setText("PLAYER 1 HEALTH: " + player1Health);
        player1Health--; lblP2Health.setText("PLAYER 2 HEALTH: " + player2Health);

        int p1 = Integer.parseInt(txt1.getText());
        int p2 = Integer.parseInt(txt2.getText());

        if(p1 == 1 &&  p2 == 1) {
            JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.ERROR_MESSAGE);
        }
        else if(p1 == 1 &&  p2 == 2) {
            JOptionPane.showMessageDialog(rootPane,"PLAYER 2 WINS", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else if(p1 == 1 && p2 == 3)
        {
            JOptionPane.showMessageDialog(rootPane,"PLAYER 1 WINS", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }

        else if(p1 == 2 && p2 == 1)
        {
            JOptionPane.showMessageDialog(rootPane,"PLAYER 1 WINS", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else if(p1 == 2 && p2 == 2)
        {
            JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.ERROR_MESSAGE);
        }
        else if(p1 == 2 && p2 == 3)
        {
            JOptionPane.showMessageDialog(rootPane,"PLAYER 1 WINS", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }

        else if(p1 == 3 && p2 == 1)
        {
            JOptionPane.showMessageDialog(rootPane,"PLAYER 2 WINS", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else if(p1 == 3 && p2 == 2)
        {
            JOptionPane.showMessageDialog(rootPane,"PLAYER 1 WINS", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else if(p1 == 3 && p2 == 3)
        {
            JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.ERROR_MESSAGE);
        }
