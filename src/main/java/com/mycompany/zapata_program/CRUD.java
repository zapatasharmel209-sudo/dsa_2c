    private void resultButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_resultButtonActionPerformed
        // TODO add your handling code here:

    try {

        double mathematics = Double.parseDouble(math.getText());
        double eng = Double.parseDouble(english.getText());
        double bio = Double.parseDouble(biology.getText());
        double chem = Double.parseDouble(chemistry.getText());
        double it = Double.parseDouble(infoTech.getText());
        double phys = Double.parseDouble(physics.getText());

        double total =
                mathematics +
                eng +
                bio +
                chem +
                it +
                phys;

        double avg = total / 6;

        totalScore.setText(String.format("%.2f", total));
        average.setText(String.format("%.2f", avg));

        if (avg >= 90) {
            ranking.setText("Excellent");
        }
        else if (avg >= 80) {
            ranking.setText("Very Good");
        }
        else if (avg >= 75) {
            ranking.setText("Passed");
        }
        else {
            ranking.setText("Failed");
        }

        System.out.println("Total Score: " + total);
        System.out.println("Average: " + avg);
        System.out.println("Ranking: " + ranking.getText());

    }
    catch (NumberFormatException e) {
        System.out.println("Please enter valid scores for all subjects.");
    }
    }//GEN-LAST:event_resultButtonActionPerformed

