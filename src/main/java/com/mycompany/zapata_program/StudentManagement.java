    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:                                      
    String search = txtSearch.getText().trim();

    if (search.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter a Student No., Name, Course, or Year Level.",
                "Search",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    String sql = "SELECT id, student_no, first_name, last_name, course, year_level "
           + "FROM student_record "
           + "WHERE student_no LIKE ? "
           + "OR first_name LIKE ? "
           + "OR last_name LIKE ? "
           + "OR (first_name & ' ' & last_name) LIKE ? "
           + "OR course LIKE ? "
           + "OR CStr(year_level) LIKE ?";

    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    try (
        Connection conn = MsAccessConnection.connect();
        PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        String keyword = "%" + search + "%";

        pst.setString(1, keyword);
        pst.setString(2, keyword);
        pst.setString(3, keyword);
        pst.setString(4, keyword);
        pst.setString(5, keyword);
        pst.setString(6, keyword);

        ResultSet rs = pst.executeQuery();

        boolean found = false;

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("student_no"),
                rs.getString("first_name"),
                rs.getString("last_name"),
                rs.getString("course"),
                rs.getString("year_level")
            });

            found = true;
        }

        if (!found) {
            JOptionPane.showMessageDialog(this,
                    "No student found.",
                    "Search",
                    JOptionPane.INFORMATION_MESSAGE);
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error searching student:\n" + e.getMessage(),
                "Search Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnSearchActionPerformed

