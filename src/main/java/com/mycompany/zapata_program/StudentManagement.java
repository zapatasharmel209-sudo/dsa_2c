    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:                                       
    String studentNo = jTextField1.getText();
    String firstName = jTextField2.getText();
    String lastName = jTextField3.getText();
    String course = jTextField4.getText();
    String yearLevel = jTextField5.getText();

    if (studentNo.isEmpty() || firstName.isEmpty() || lastName.isEmpty()
            || course.isEmpty() || yearLevel.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.");
        return;
    }

    String sql = "INSERT INTO student_record "
            + "(student_no, first_name, last_name, course, year_level) "
            + "VALUES (?, ?, ?, ?, ?)";

    try (
        Connection conn = MsAccessConnection.connect();
        PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        pst.setString(1, studentNo);
        pst.setString(2, firstName);
        pst.setString(3, lastName);
        pst.setString(4, course);
        pst.setString(5, yearLevel);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Student added successfully!");

        loadStudents();

        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField5.setText("");

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error adding student:\n" + e.getMessage());
    
}
    }//GEN-LAST:event_jButton1ActionPerformed

